# https://catalogue.dataspace.copernicus.eu/odata/v1/Bursts?$top=50&$filter=ParentProductName%20eq%20%27S1C_IW_SLC__1SDV_20260408T174632_20260408T174659_007128_00E6F6_E998.SAFE%27

ALLOWED_INSTRUMENT_MODES = {"IW", "EW", "SM"}

# Shared folder used by the S1-ARD processor to write its temporary files
TEMPORARY_FOLDER = "/mnt/share/ads-01"

# HACK for the REFERENCE_DB generated by the reference pipeline: it is not an output product of the task table, but
# an auxiliary file (ADF) of the pipeline, that the processor fills. It is still the result of the processing, so:
# - the process-s1-ard-reference flow allocates its folder, s3://<bucket>/<owner>/s01_adf_refdb/<uuid>,
# - the folder is given to the generic processing flow by its S1ARD_REFERENCE_DB_PATH context variable: the generic
#   flow adds it to the ADFs of the payload, see build_and_generate_payload(),
# - after the processing, the process-s1-ard-reference flow publishes it in the s01_adf_refdb collection, as if
#   it was an output product.
# The nominal process-s1-ard flow, without reference date, finds the REFERENCE_DB of the track of its SLCs in the
# s01_adf_refdb collection, and gives its folder to the generic processing flow the same way: the processor
# reads the master SLC and its reference geometry from it.
REFERENCE_DB_COLLECTION = "s01_adf_refdb"
REFERENCE_DB_PRODUCT_TYPE = "ADF_REFDB"

# Instrument modes that can use a REFERENCE_DB: for the SM mode (no bursts), the processor requires a reference date
REFERENCE_DB_INSTRUMENT_MODES = {"IW", "EW"}

# Suffix of the pipelines of the task table that read the REFERENCE_DB, e.g. SLC__1_NRB__1_FROM_REFERENCE_DB, instead
# of recomputing the reference geometry of the master SLC given by the reference date (single shot)
FROM_REFERENCE_DB_SUFFIX = "_FROM_REFERENCE_DB"

# Properties of the master SLC item copied to the REFERENCE_DB item
REFERENCE_DB_SLC_PROPERTIES = (
    "start_datetime",
    "end_datetime",
    "platform",
    "constellation",
    "instruments",
    "sar:instrument_mode",
    "sat:orbit_state",
    "sat:relative_orbit",
)


def _get_slc_collection(slc: str, input_collections: list[str]) -> str:
    """
    Return the catalog collection of an S1 SLC product, based on the instrument mode in its name.

    Args:
        slc (str): STAC item identifier of the S1 SLC product, e.g. S1C_IW_SLC__1SDV_...
        input_collections (list[str]): Catalog collection names containing the S1 SLC products,
        e.g. s01sewslc, s01siwslc, s01ssmslc, or s1-l1-ew-slc, s1-l1-iw-slc, s1-l1-sm-slc for the legacy SLCs.

    Returns:
        str: The collection whose name ends with the instrument mode (IW, EW, or SM for S1..S6 stripmap modes)
        followed by "slc", with an optional "-" or "_" separator, or the first collection if no match is found.
    """
    match = re.match(r"^S1[A-Z]_(IW|EW|S[1-6])_", slc)
    if match:
        mode = "sm" if match.group(1).startswith("S") else match.group(1).lower()
        mode_regex = re.compile(rf"{mode}[-_]?slc$", re.IGNORECASE)
        collection = next((c for c in input_collections if mode_regex.search(c)), None)
        if collection:
            return collection
    return input_collections[0]


def _check_slcs(slcs: list[str]) -> bool:
    """Check the input SLCs. Return False if the processing cannot be launched."""
    if not slcs:
        get_run_logger().error("❌ The processing cannot be launched, no SLC provided")
        return False
    return True


def _get_instrument_mode(items: list[Item]) -> str | None:
    """Return the instrument mode shared by all the items, or None if they are invalid or different."""
    logger = get_run_logger()
    modes: list[str] = [item.properties.get("sar:instrument_mode", "") for item in items]
    invalid_modes = [mode for mode in modes if mode not in ALLOWED_INSTRUMENT_MODES]
    if invalid_modes:
        logger.error(
            f"❌ Invalid sar:instrument_mode values found: {invalid_modes}. "
            f"Allowed values are {sorted(ALLOWED_INSTRUMENT_MODES)}",
        )
        return None

    unique_modes = set(modes)
    if len(unique_modes) != 1:
        logger.error(f"❌ Items do not share the same sar:instrument_mode: {sorted(unique_modes)}")
        return None
    return unique_modes.pop()


def _build_external_variables(
    instrument_mode: str,
    slcs: list[str],
    reference_date: date | None,
    pipeline: str | None,
) -> dict[str, str]:
    """Build the external variables passed to the DPR processor."""
    external_variables = {"instrument_mode": instrument_mode}
    if pipeline == "SLC__1_NRB__1" and not reference_date:
        # Reference date is required to fetch S2_TILES aux file (mosaicking step only)
        match = re.search(r"(\d{8})T", slcs[0])
        if match:
            reference_date = datetime.strptime(match.group(1), "%Y%m%d").date()
    if reference_date:
        external_variables["reference_date"] = str(reference_date)
    return external_variables


def _allocate_reference_db_path(owner_id: str) -> str:
    """
    Return a new folder for the REFERENCE_DB generated by the reference pipeline:
    s3://<bucket>/<owner>/s01_adf_refdb/<uuid>, the bucket being given by the bucket configuration for the owner,
    the s01_adf_refdb collection and the ADF_REFDB product type.
    """
    bucket_configuration = fetch_csv_from_endpoint(os.environ["RSPY_HOST_OSAM"] + "/internal/configuration")
    bucket_name = find_s3_output_bucket(
        bucket_configuration,
        owner_id,
        REFERENCE_DB_COLLECTION,
        REFERENCE_DB_PRODUCT_TYPE,
    )
    return os.path.join("s3://", bucket_name, owner_id, REFERENCE_DB_COLLECTION, str(uuid4()))


def _build_reference_db_item(reference_db_path: str, slc_item: Item) -> Item:
    """
    Build the STAC item of the REFERENCE_DB generated by the reference pipeline from a master SLC.

    Args:
        reference_db_path: Folder of the REFERENCE_DB. Its last part (uuid) is the item ID.
        slc_item: STAC item of the master SLC: the REFERENCE_DB item gets its geometry, dates, platform and orbit, and
        is derived from it.
    """
    properties = {key: slc_item.properties[key] for key in REFERENCE_DB_SLC_PROPERTIES if key in slc_item.properties}
    properties["product:type"] = REFERENCE_DB_PRODUCT_TYPE
    properties["created"] = datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")
    item_id = reference_db_path.rstrip("/").rsplit("/", 1)[-1]
    item = Item(
        id=item_id,
        geometry=slc_item.geometry,
        bbox=slc_item.bbox,
        datetime=slc_item.datetime,
        properties=properties,
        stac_extensions=[],
        assets={
            "REFERENCE_DB": Asset(
                href=reference_db_path,
                title=f"REFERENCE_DB {item_id}",
                media_type="application/vnd+zarr",
                roles=["data"],
            ),
        },
    )
    # Relative link to the master SLC, as for the output products of the generic processing flow
    if slc_href := slc_item.get_self_href():
        parsed_href = urlsplit(slc_href)
        item.add_derived_from(urlunsplit(("", "", parsed_href.path, parsed_href.query, parsed_href.fragment)))
    return item


async def _publish_reference_db(flow_env: FlowEnv, reference_db_path: str, slc_item: Item) -> None:
    """Publish the REFERENCE_DB generated by the reference pipeline in the s01_adf_refdb collection."""
    item = _build_reference_db_item(reference_db_path, slc_item)
    published = await catalog_flow.publish(
        flow_env.serialize(),
        [
            FlowGeneratedProduct(
                name=item.id,
                product_type=REFERENCE_DB_PRODUCT_TYPE,
                collection_name=REFERENCE_DB_COLLECTION,
            ),
        ],
        [
            DprProcessedItemMetadata(
                output_product_id=item.id,
                product_type=REFERENCE_DB_PRODUCT_TYPE,
                stac_item=item,
            ),
        ],
    )
    # The publish task only logs a warning when the catalog rejects an item
    if not published:
        raise RuntimeError(
            f"❌ The REFERENCE_DB {reference_db_path} was generated but not published in {REFERENCE_DB_COLLECTION!r}",
        )
    get_run_logger().info(f"✅ REFERENCE_DB {item.id!r} published in {REFERENCE_DB_COLLECTION!r}: {reference_db_path}")


def _reference_db_filter(slc_items: list[Item]) -> dict:
    """
    Return the CQL2 filter of the REFERENCE_DB items generated from a master SLC of the same track as the SLCs:
    same instrument mode, relative orbit and orbit direction (when given).

    Raises:
        ValueError: If the SLCs have no relative orbit, or are not on the same track.
    """
    track_properties = ("sar:instrument_mode", "sat:relative_orbit", "sat:orbit_state")
    args: list[dict] = [{"op": "=", "args": [{"property": "product:type"}, REFERENCE_DB_PRODUCT_TYPE]}]
    for key in track_properties:
        values = {item.properties.get(key) for item in slc_items}
        if len(values) != 1:
            raise ValueError(f"❌ The SLCs are not on the same track, they have several {key!r} values: {values}")
        value = values.pop()
        if value is None:
            if key == "sat:orbit_state":
                continue
            raise ValueError(
                f"❌ The SLCs have no {key!r} property to search their REFERENCE_DB in {REFERENCE_DB_COLLECTION!r}: "
                "give the REFERENCE_DB item ID with the reference_db parameter",
            )
        args.append({"op": "=", "args": [{"property": key}, value]})
    return {"op": "and", "args": args}


async def _find_reference_db(flow_env: FlowEnv, slc_items: list[Item], reference_db: str | None) -> str:
    """
    Return the folder of the REFERENCE_DB read by the processing of the SLCs, from the s01_adf_refdb
    collection: the given item, or else the latest REFERENCE_DB generated by the reference pipeline from a master
    SLC of the same track as the SLCs, that intersects the first SLC.

    Raises:
        ValueError: If the REFERENCE_DB is not found.
    """
    logger = get_run_logger()
    catalog_client = flow_env.rs_client.get_catalog_client()
    if reference_db:
        _, path = resolve_stac_input_path(catalog_client, REFERENCE_DB_COLLECTION, reference_db)
        logger.info(f"🛈 REFERENCE_DB {reference_db!r} given as parameter: {path}")
        return path

    stac_filter = _reference_db_filter(slc_items)
    found = catalog_client.search(
        method="POST",
        collections=[REFERENCE_DB_COLLECTION],
        stac_filter=stac_filter,
        intersects=slc_items[0].geometry,
        sortby=[{"field": "created", "direction": "desc"}],
        max_items=1,
        limit=1,
    )
    if not found or len(found) == 0:
        raise ValueError(
            f"❌ No REFERENCE_DB found in {REFERENCE_DB_COLLECTION!r} for the track of the SLCs "
            f"({json.dumps(stac_filter)}): run the process-s1-ard-reference flow on a master SLC of this track first, "
            "or give a reference_date to recompute the reference geometry of the master SLC (single shot)",
        )
    item = found.items[0]
    found_path = get_first_asset_dir(item)
    if not found_path:
        raise ValueError(f"❌ The REFERENCE_DB item {item.id!r} of {REFERENCE_DB_COLLECTION!r} has no asset")
    masters = [link.target for link in item.links if link.rel == "derived_from"]
    logger.info(f"🛈 REFERENCE_DB {item.id!r} found, generated from the master SLC {masters}: {found_path}")
    return found_path


async def _prepare_reference_db(  # pylint: disable=too-many-arguments, too-many-positional-arguments
    flow_env: FlowEnv,
    pipeline: str | None,
    reference_date: date | None,
    instrument_mode: str,
    slc_items: list[Item],
    reference_db: str | None,
) -> tuple[str | None, str | None]:
    """
    HACK for the REFERENCE_DB: return the pipeline to run, and the folder of the REFERENCE_DB to give to the
    processor, or None. The collection of the REFERENCE_DB is checked before processing anything.

    - Reference pipeline: a new folder, where the processor writes the REFERENCE_DB.
    - Without reference date: the `<pipeline>_FROM_REFERENCE_DB` pipeline, and the folder of the REFERENCE_DB found
      in the catalog, that the processor reads (IW and EW modes only).
    - With a reference date (single shot): the given pipeline, without REFERENCE_DB, as the processor recomputes the
      reference geometry of the master SLC of this date.

    Raises:
        ValueError: If the REFERENCE_DB cannot be used, or is not found.
    """
    logger = get_run_logger()
    if pipeline == DprPipeline.S1ARD_REF.value:
        await catalog_flow.check_collections_exist(flow_env, [REFERENCE_DB_COLLECTION])
        reference_db_path = _allocate_reference_db_path(flow_env.owner_id)
        logger.info(f"🛈 The REFERENCE_DB will be written in: {reference_db_path}")
        return pipeline, reference_db_path

    if reference_date:
        if reference_db:
            logger.warning(
                f"⚠️ The REFERENCE_DB {reference_db!r} is not used with a reference_date: the processor recomputes the "
                "reference geometry of the master SLC (single shot)",
            )
        return pipeline, None

    if not pipeline:
        raise ValueError(
            "❌ A pipeline is required without reference_date, to run its variant that reads the REFERENCE_DB",
        )
    if instrument_mode not in REFERENCE_DB_INSTRUMENT_MODES:
        raise ValueError(
            f"❌ A reference_date is required for the {instrument_mode} instrument mode: the processor can only use a "
            f"REFERENCE_DB for the {sorted(REFERENCE_DB_INSTRUMENT_MODES)} modes",
        )
    await catalog_flow.check_collections_exist(flow_env, [REFERENCE_DB_COLLECTION])
    reference_db_path = await _find_reference_db(flow_env, slc_items, reference_db)
    if not pipeline.endswith(FROM_REFERENCE_DB_SUFFIX):
        pipeline += FROM_REFERENCE_DB_SUFFIX
    return pipeline, reference_db_path


async def _do_process_s1ard(  # pylint: disable=too-many-arguments, too-many-positional-arguments
    slcs: list[str],
    reference_date: date | None,
    env_args: FlowEnvArgs,
    pipeline: str | None,
    reference_db: str | None = None,
):
    """
    Sentinel-1 ARD processing (common function for reference pipeline and nominal on-demand flow), with the settings
    of the `s1ard-default-setting` Prefect variable.

    Args:
        slcs (list[str]): STAC item identifiers of S1 SLC input products, already converted to zarr.
        A single item for the reference pipeline.
        reference_date (date | None): Date of the master (reference) SLC, to recompute its reference geometry
        (single shot), or None to read it from the REFERENCE_DB of the catalog. Set to None for reference pipeline
        env_args (FlowEnvArgs): Flow environment arguments
        pipeline (str | None): Pipeline to run, or None to run the pipeline of the settings
        reference_db (str | None): Item ID of the REFERENCE_DB in the catalog, without reference date. By default, the
        latest REFERENCE_DB of the track of the SLCs.
    """
    logger = get_run_logger()

    if not _check_slcs(slcs):
        return

    # Read the Prefect blocks into env vars (e.g. DASK_GATEWAY_ADDRESS), needed to check the Dask clusters
    flow_env = FlowEnv(env_args)

    # The EarthDataHub API key, used to read the Copernicus DEM, is read from the Prefect blocks of the owner,
    # not from the flow parameters that can be read by everyone in the Prefect UI.
    if not os.getenv(EDH_API_KEY_ENV_VAR):
        logger.error(
            f"❌ The processing cannot be launched, set the EarthDataHub API key as {EDH_API_KEY_ENV_VAR!r} in the "
            f"'env-vars-{env_args.owner_id}' (or 'env-vars') Prefect secret block",
        )
        return

    # Read the settings and check the Dask clusters before searching the SLCs
    settings = await load_processor_settings(ProcessingId.S1_ARD, flow_env)
    pipeline = pipeline or settings.pipeline
    input_collections = settings.input_collections or DEFAULT_INPUT_COLLECTIONS
    mission = "1"
    suffix = "-reference" if pipeline == DprPipeline.S1ARD_REF.value else ""
    # start_span is a context manager (decorated with _agnosticcontextmanager), not detected by sonar
    with flow_env.start_span(__name__, f"sentinel{mission}-level1ard-processing{suffix}"):  # NOSONAR
        item_collection: ItemCollection | None = await get_catalog_items(flow_env, slcs, input_collections)
        if not item_collection or len(item_collection) == 0:
            logger.error(f"❌ The processing cannot be launched, no items found for {slcs} in {input_collections}")
            return

        instrument_mode = _get_instrument_mode(item_collection.items)
        if not instrument_mode:
            return

        input_products = [
            FlowInputProduct(
                name="slcs",
                item_id=slc,
                collection_name=_get_slc_collection(slc, input_collections),
            )
            for slc in slcs
        ]

        # External variables of the given pipeline, before choosing the pipeline that reads the REFERENCE_DB
        external_variables = _build_external_variables(instrument_mode, slcs, reference_date, pipeline)

        # HACK for the REFERENCE_DB: give its folder to the generic processing flow
        pipeline, reference_db_path = await _prepare_reference_db(
            flow_env,
            pipeline,
            reference_date,
            instrument_mode,
            item_collection.items,
            reference_db,
        )
        token = S1ARD_REFERENCE_DB_PATH.set(reference_db_path)

        # Call DPR flow
        try:
            await call_dpr_flow(
                env_args,
                settings=settings,
                input_products=input_products,
                external_variables=external_variables,
                workflow=WorkflowType.ON_DEMAND,
                pipeline=pipeline,
                dask_task_timeout=3000,
                temporary_folder=TEMPORARY_FOLDER,
                temporary_shared=True,
            )
        finally:
            S1ARD_REFERENCE_DB_PATH.reset(token)

        # The REFERENCE_DB generated by the reference pipeline is published as if it was an output product
        if pipeline == DprPipeline.S1ARD_REF.value and reference_db_path:
            await _publish_reference_db(flow_env, reference_db_path, item_collection.items[0])


@flow(name="process-s1-ard")
async def process_s1ard(
    slcs: list[str],
    reference_date: date | None,
    env_args: FlowEnvArgs,
    pipeline: S1ArdPipeline | None = None,
    reference_db: str | None = None,
):
    """
    Sentinel-1 ARD processing (nominal on-demand flow).

        Args:
            slcs: STAC item identifiers of S1 SLC input products, already converted to zarr.
            reference_date: Date of the master (reference) SLC, that must be in the SLCs: the processor recomputes
                its reference geometry (single shot). Or None to read the master SLC and its geometry from the
                REFERENCE_DB generated by the process-s1-ard-reference flow, found in the catalog (IW and EW only).
            env_args: Flow environment arguments, the owner Prefect blocks must contain the EarthDataHub API key
            pipeline: Pipeline to run (default: the pipeline of the `s1ard-default-setting` Prefect variable). Without
                reference date, its `<pipeline>_FROM_REFERENCE_DB` variant is run.
            reference_db: Item ID of the REFERENCE_DB in the `s01_adf_refdb` collection, without reference
                date. By default, the latest REFERENCE_DB of the track (instrument mode, relative orbit, orbit
                direction) of the SLCs, that intersects the first SLC.
    """

    # Specific data used for tests:
    # https://stac.dataspace.copernicus.eu/v1/collections/sentinel-1-slc/items/S1D_IW_SLC__1SDV_20260420T055953_20260420T060020_002426_003FB6_3AE6
    # https://stac.dataspace.copernicus.eu/v1/collections/sentinel-1-slc/items/S1C_IW_SLC__1SDV_20260408T174632_20260408T174659_007128_00E6F6_E998
    # https://stac.dataspace.copernicus.eu/v1/collections/sentinel-1-slc/items/S1C_IW_SLC__1SDV_20260327T174632_20260327T174659_006953_00E115_D167

    # https://earthdatahub.destine.eu/api/stac/v1/collections/copernicus-dem/items/GLO-30

    await _do_process_s1ard(slcs, reference_date, env_args, pipeline, reference_db)


@flow(name="process-s1-ard-reference")
async def process_s1ard_reference(slc: str, env_args: FlowEnvArgs):
    """
    Sentinel-1 ARD processing reference pipeline.
    This flow must be run once to generate the REFERENCE_DB used in on-demand S1 ARD processing flow.

        Args:
            slc: STAC item identifier of S1 master SLC input product, already converted to zarr.
            env_args: Flow environment arguments, the owner Prefect blocks must contain the EarthDataHub API key
    """
    await _do_process_s1ard([slc], None, env_args, DprPipeline.S1ARD_REF.value)


@task(name="process sentinel-1 level-1-ard")
async def process_s1l1ard_task(*args, **kwargs) -> None:
    """See: dpr_processing"""
    return await process_s1ard.fn(*args, **kwargs)


@task(name="process sentinel-1 level-1-ard reference pipeline")
async def process_s1l1ard_reference_task(*args, **kwargs) -> None:
    """See: dpr_processing"""
    return await process_s1ard_reference.fn(*args, **kwargs)
